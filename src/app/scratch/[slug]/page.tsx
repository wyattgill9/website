import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import Container from "../../components/container";
import InlineMd, { LINK } from "../../components/inline-md";
import TopNav from "../../components/top-nav";
import { formatDate, loadPost, POSTS } from "../posts";

type Props = { params: Promise<{ slug: string }> };

export const dynamicParams = false;

export function generateStaticParams() {
    return POSTS.map(({ slug }) => ({ slug }));
}

export async function generateMetadata({ params }: Props): Promise<Metadata> {
    const post = loadPost((await params).slug);
    return post ? { title: post.title, description: post.dek } : {};
}

export default async function Post({ params }: Props) {
    const post = loadPost((await params).slug);
    if (!post) notFound();

    return (
        <div className="min-h-screen w-full bg-background text-foreground">
            <TopNav solid />
            <Container as="main" className="pb-24 pt-28">
                {/* Mono for the chrome, like the rest of the site; sans for the long-form body so it reads. */}
                <article className="max-w-[68ch] font-geistSans text-[16px] leading-[1.75]">
                    <header className="mb-12 font-geistMono">
                        <Link
                            href="/scratch"
                            className="text-[12px] lowercase tracking-[0.04em] opacity-50 transition-opacity hover:opacity-100"
                        >
                            ← scratch
                        </Link>
                        <h1 className="mt-6 text-balance text-[22px] font-medium leading-[1.3]">{post.title}</h1>
                        <time dateTime={post.date} className="mt-3 block text-[12px] tabular-nums opacity-50">
                            {formatDate(post.date)}
                        </time>
                        {post.ai && (
                            <p className="mt-6 border-l border-[color-mix(in_srgb,var(--foreground-color)_25%,transparent)] pl-3 text-[12px] leading-[1.6] opacity-70">
                                This article was generated by AI. Check its figures against primary sources before
                                relying on them.
                            </p>
                        )}
                        {post.dek && (
                            <p className="mt-6 font-geistSans text-[17px] leading-[1.6] opacity-70">
                                <InlineMd text={post.dek} />
                            </p>
                        )}
                    </header>
                    {post.blocks.map(({ type, text, src }, i) =>
                        type === "embed" ? (
                            // Wider than the text column: the diagram is a wide org chart. On lg the
                            // container gutter is 20vw, so pull back to a 1.5rem page margin.
                            <figure key={i} className="my-10 lg:-ml-[calc(20vw-1.5rem)] lg:w-[calc(100vw-3rem)]">
                                <iframe
                                    src={src}
                                    title={text}
                                    loading="lazy"
                                    className="h-[80vh] max-h-[900px] min-h-[480px] w-full rounded-md border border-[color-mix(in_srgb,var(--foreground-color)_12%,transparent)]"
                                />
                                <figcaption className="mt-2 flex justify-between gap-4 font-geistMono text-[12px] opacity-50">
                                    <span>{text}</span>
                                    <a href={src} target="_blank" rel="noopener noreferrer" className={LINK}>
                                        full screen ↗
                                    </a>
                                </figcaption>
                            </figure>
                        ) : type === "h2" ? (
                            <h2
                                key={i}
                                className="mb-4 mt-14 border-t border-[color-mix(in_srgb,var(--foreground-color)_12%,transparent)] pt-8 font-geistMono text-[15px] font-medium"
                            >
                                {text}
                            </h2>
                        ) : type === "h3" ? (
                            <h3
                                key={i}
                                className="mb-3 mt-10 font-geistMono text-[13px] lowercase tracking-[0.04em] opacity-60"
                            >
                                {text}
                            </h3>
                        ) : type === "hr" ? (
                            <hr
                                key={i}
                                className="my-10 border-[color-mix(in_srgb,var(--foreground-color)_12%,transparent)]"
                            />
                        ) : (
                            <p key={i} className="mb-5 text-pretty">
                                <InlineMd text={text} />
                            </p>
                        )
                    )}
                </article>
            </Container>
        </div>
    );
}
